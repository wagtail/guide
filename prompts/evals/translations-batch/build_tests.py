"""Generate the batch-translation eval test files from documents.json.

documents.json holds real full-page segment lists exported from
wagtail-localize TranslationSources (id, vars.doc as a JSON string of
{"id", "text"} cases). This script expands them into:

- tests-batch.yaml    one test per document x envelope format (xml/json),
                      with the source document pre-rendered in both
                      envelopes for the llm-rubric judge.
- tests-segments.yaml one test per unique segment (flat), tagged with the
                      document it came from, for the per-segment baseline.

Both are committed; re-run this script after regenerating documents.json:

    uv run python prompts/evals/translations-batch/build_tests.py
"""

import json
from pathlib import Path

import yaml

HERE = Path(__file__).parent


def render_xml(cases):
    lines = ["<document>"]
    for case in cases:
        lines.append(f'<segment id="{case["id"]}">{case["text"]}</segment>')
    lines.append("</document>")
    return "\n".join(lines)


def render_json(cases):
    return json.dumps(cases, ensure_ascii=False, indent=2)


def main():
    docs = json.loads((HERE / "documents.json").read_text(encoding="utf-8"))

    batch_tests = []
    segment_tests = []
    for doc in docs:
        cases = json.loads(doc["vars"]["doc"])
        for fmt, render in (
            ("xml", render_xml),
            ("json", render_json),
            ("json-schema", render_json),
        ):
            batch_tests.append(
                {
                    "description": f"{doc['description']} — {fmt.upper()} envelope",
                    "metadata": {
                        "id": f"{doc['id']}-{fmt}",
                        "doc_id": doc["id"],
                        "format": fmt,
                    },
                    "vars": {
                        "format": fmt,
                        "doc": doc["vars"]["doc"],
                        "src_doc": render(cases),
                    },
                }
            )
        for case in cases:
            segment_tests.append(
                {
                    "description": f"{doc['description']} — segment {case['id']}",
                    "metadata": {
                        "id": f"{doc['id']}-{case['id']}",
                        "doc_id": doc["id"],
                    },
                    "vars": {"text": case["text"]},
                }
            )

    for name, tests in (
        (
            "tests-batch.yaml",
            [t for t in batch_tests if t["vars"]["format"] != "json-schema"],
        ),
        (
            "tests-batch-schema.yaml",
            [t for t in batch_tests if t["vars"]["format"] == "json-schema"],
        ),
        ("tests-segments.yaml", segment_tests),
    ):
        path = HERE / name
        header = (
            "# Generated by build_tests.py from documents.json — do not edit by hand.\n"
        )
        path.write_text(
            header
            + yaml.safe_dump(tests, allow_unicode=True, sort_keys=False, width=100),
            encoding="utf-8",
        )
        print(f"wrote {path} ({len(tests)} tests)")


if __name__ == "__main__":
    main()
